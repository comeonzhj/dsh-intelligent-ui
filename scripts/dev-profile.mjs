#!/usr/bin/env node
/**
 * Set up and boot a scratch profile that runs this plugin, without touching the
 * profile you actually use.
 *
 * The desktop app is the `desktop` profile; it is never read or written here.
 * Everything happens in a profile named after this package, and the plugin is
 * mounted through a `--patch` overlay rather than an install, for two reasons:
 *
 *   * a patch row naming an **absolute path** needs no `node_modules`, no pnpm
 *     and no network, and the client half still resolves — the module registry
 *     takes the nearest ancestor `package.json` of the row's module and reads
 *     its `dsh.client` manifest;
 *   * the overlay is applied last and lives outside the profile, so nothing
 *     else can rewrite it.
 *
 * Usage:
 *   node scripts/dev-profile.mjs                 # write the overlay, then print the command
 *   node scripts/dev-profile.mjs --boot          # write the overlay, then boot it
 *   node scripts/dev-profile.mjs --boot --port 3091
 *   node scripts/dev-profile.mjs --overlay-only
 *
 * @module intelligent-ui/scripts/dev-profile
 */

import { mkdir, readFile, writeFile, access } from 'node:fs/promises'
import { spawn } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import os from 'node:os'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, '..')
const manifest = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'))

const argv = process.argv.slice(2)
const boot = argv.includes('--boot')
const overlayOnly = argv.includes('--overlay-only')
const portArg = argv.indexOf('--port')
const port = portArg === -1 ? '3091' : argv[portArg + 1]
const profile = (() => {
  const at = argv.indexOf('--profile')
  return at === -1 ? 'intelligent-ui-dev' : argv[at + 1]
})()

const overlayPath = path.join(os.tmpdir(), `${manifest.name}-dev.cordis.yml`)
const profileDir = path.join(os.homedir(), '.dsh', 'profiles', profile)

/**
 * The overlay.
 *
 * Both `llm-pi-ai` and `agent-default-model` already exist as rows in
 * `dsh-base`; a patch replaces a row's whole `config`, so every field the row
 * needs is restated. Point `baseURL` at whatever gateway answers on this
 * machine — the default below is the one the desktop profile uses.
 */
const overlay = `# Generated by ${manifest.name}/scripts/dev-profile.mjs — do not commit.
#
# Mounts this checkout as a plugin row and points the default model at a local
# gateway. Applied last, and outside the profile, so nothing can rewrite it.

- id: llm-pi-ai
  name: '@deepseek-ai/dsh-llm-pi-ai'
  config:
    providers:
      magpie:
        displayName: Magpie
        apiKeyEnv: MAGPIE_GATEWAY_KEY
        api: openai-completions
        baseURL: http://127.0.0.1:3425/v1
        models:
          - id: tsinghua/DeepSeek-V4.1-Flash
            name: DeepSeek V4.1 Flash · tsinghua
            contextWindow: 1048576
            maxTokens: 384000
            input: [text, image]

- id: agent-default-model
  config:
    provider: magpie
    model: 'tsinghua/DeepSeek-V4.1-Flash'

# The desktop app pins the transcript view to standard, which folds every tool
# call behind the turn's completion disclosure. A web profile defaults to
# detailed, where tool calls render in place, so the card is visible without a
# click.
- id: ui-chat
  name: '@deepseek-ai/dsh-client-ui-chat'
  config:
    transcriptView: detailed
    performanceUsage: detailed

- insert:
    - id: intelligent-ui
      name: '${path.join(root, 'index.js')}'
      config:
        prompt: true
        detail: full
        language: zh
`

await writeFile(overlayPath, overlay, 'utf8')
process.stdout.write(`overlay  ${overlayPath}\n`)

if (overlayOnly) process.exit(0)

async function exists(target) {
  try { await access(target); return true } catch { return false }
}

const profileExists = await exists(path.join(profileDir, 'package.json'))
const commands = []
if (!profileExists) {
  commands.push(`dsh --profile ${profile} --from-default-profile web --dump-config`)
}
commands.push(`dsh --profile ${profile} --patch ${overlayPath} --port ${port} --no-open`)

process.stdout.write(`profile  ${profileDir}${profileExists ? '' : '  (will be created)'}\n\n`)
for (const command of commands) process.stdout.write(`  ${command}\n`)
process.stdout.write('\n')

if (!boot) {
  process.stdout.write('Re-run with --boot to start it. The URL it prints carries the auth token.\n')
  process.exit(0)
}

if (!profileExists) {
  process.stdout.write('Creating the profile...\n')
  const created = spawn('dsh', ['--profile', profile, '--from-default-profile', 'web', '--dump-config'], {
    stdio: ['ignore', 'ignore', 'inherit'],
  })
  const code = await new Promise((resolve) => created.on('close', resolve))
  if (code !== 0) {
    process.stderr.write(`could not create the profile (exit ${code})\n`)
    process.exit(code ?? 1)
  }
  await mkdir(profileDir, { recursive: true })
}

process.stdout.write('Booting. Ctrl-C to stop.\n')
spawn('dsh', ['--profile', profile, '--patch', overlayPath, '--port', port, '--no-open'], { stdio: 'inherit' })
